// After adding or changing translations, from app/: node scripts/i18n-sync.mjs
// 1. src/i18n/index.ts: one lazy require per language file in src/i18n/.
// 2. locales/<tag>.json: the iOS permission texts (native.* keys) per language, for app.json `locales`.
// 3. app.json: `locales`, CFBundleAllowMixedLocalizations, and expo-localization's supportedLocales (per-app language
//    choice in Settings, and right-to-left layout on iOS).
// 4. ../server/i18n.json: the server's error messages and push title per language.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

const at = (p) => new URL(p, import.meta.url);
const LANGS = JSON.parse(readFileSync(at('../../store/i18n/languages.json'), 'utf8'));
const tags = readdirSync(at('../src/i18n/')).filter((f) => f.endsWith('.json') && f !== 'en.json').map((f) => f.slice(0, -5))
  .filter((t) => LANGS[t]).sort();

writeFileSync(at('../src/i18n/index.ts'), `// Every shipped language except English (en.json), loaded on first use. Generated by scripts/i18n-sync.mjs.
export const DICTS: Record<string, () => Record<string, string>> = {
${tags.map((t) => `  '${t}': () => require('./${t}.json'),`).join('\n')}
};
`);

mkdirSync(at('../locales/'), { recursive: true });
const locales = {};
for (const t of tags) {
  const d = JSON.parse(readFileSync(at(`../src/i18n/${t}.json`), 'utf8'));
  const ios = Object.fromEntries(Object.entries(d).filter(([k]) => k.startsWith('native.')).map(([k, v]) => [k.slice(7), v]));
  const tag = LANGS[t].platform;
  writeFileSync(at(`../locales/${tag}.json`), JSON.stringify({ ios }, null, 2) + '\n');
  locales[tag] = `./locales/${tag}.json`;
}

// 4. ../server/i18n.json: the server's own messages (server.*, push.*), keyed by their English text.
const EN = JSON.parse(readFileSync(at('../src/i18n/en.json'), 'utf8'));
const server = {};
for (const t of tags) {
  const d = JSON.parse(readFileSync(at(`../src/i18n/${t}.json`), 'utf8'));
  server[t] = Object.fromEntries(Object.keys(EN).filter((k) => /^(server|push)\./.test(k) && d[k]).map((k) => [EN[k], d[k]]));
}
writeFileSync(at('../../server/i18n.json'), JSON.stringify(server, null, 1) + '\n');

const app = JSON.parse(readFileSync(at('../app.json'), 'utf8'));
const e = app.expo;
e.locales = locales;
e.ios.infoPlist = { ...e.ios.infoPlist, CFBundleAllowMixedLocalizations: true };
const supported = ['en', ...tags.map((t) => LANGS[t].platform)];
const plugin = ['expo-localization', { supportedLocales: supported }];
const i = e.plugins.findIndex((p) => (Array.isArray(p) ? p[0] : p) === 'expo-localization');
if (i >= 0) e.plugins[i] = plugin; else e.plugins.push(plugin);
writeFileSync(at('../app.json'), JSON.stringify(app, null, 2) + '\n');
console.log(`${tags.length} languages synced: ${supported.join(' ')}`);
